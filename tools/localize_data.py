FILES = {
    "src/species.c": SPECIES + KEYSTONES + SUB_UPGRADES,
    "src/evolution.c": MUTATIONS + SYNERGIES,
    "src/environment.c": ENVIRONMENTS,
}


def main(root):
    total_ok = 0
    total_miss = 0
    for rel, entries in FILES.items():
        path = os.path.join(root, rel)
        with io.open(path, "r", encoding="utf-8") as f:
            text = f.read()
        missing = []
        for en, cn, en_desc, cn_desc in entries:
            for src, dst in ((en, cn), (en_desc, cn_desc)):
                token = '"%s"' % src
                if token in text:
                    text = text.replace(token, '"%s"' % dst)
                    total_ok += 1
                else:
                    missing.append(src)
                    total_miss += 1
        with io.open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("%-24s replaced, missing %d" % (rel, len(missing)))
        for m in missing:
            print("    MISS: %s" % m)
    print("TOTAL ok=%d miss=%d" % (total_ok, total_miss))
    return 0 if total_miss == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "."))
