#define COUNT_OF(a) ((int)(sizeof(a) / sizeof((a)[0])))
_Static_assert(COUNT_OF(species) == SPECIES_COUNT, "Update species codex text for every new ID");
_Static_assert(COUNT_OF(mutations) == MUTATION_COUNT, "Update mutation codex text for every new ID");

int codex_count(CodexKind kind)
{
    return kind == CODEX_SPECIES ? COUNT_OF(species)
         : kind == CODEX_MUTATION ? COUNT_OF(mutations) : 0;
}

const CodexEntry *codex_entry(CodexKind kind, int id)
{
    if (id < 0 || id >= codex_count(kind)) return NULL;
    return kind == CODEX_SPECIES ? &species[id] : &mutations[id];
}
